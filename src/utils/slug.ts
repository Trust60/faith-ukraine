/**
 * Перетворює довільний рядок у URL-сумісний slug: нижній регістр, пробіли та
 * розділові знаки → дефіси, обрізані дефіси по краях. Лишає літери/цифри
 * (включно з юнікодом), тож працює і з латиницею, і з кирилицею.
 */
export function formatSlug(value: string): string {
  return value
    .toLowerCase()
    .trim()
    .replace(/[^\p{L}\p{N}]+/gu, "-")
    .replace(/^-+|-+$/g, "");
}
